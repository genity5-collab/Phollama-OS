#!/usr/bin/env node
'use strict';
/**
 * Nova 1.0 training pipeline — run by the agent (or anyone), NOT in the user's face:
 *
 *   1. edit train/corpus.txt  (the conversation Nova should learn)
 *   2. node train/train.js    (trains here, writes js/base-checkpoint.js)
 *   3. git commit + push      (GitHub Pages redeploys the site automatically)
 *
 * The produced checkpoint becomes the DEFAULT weights every visitor loads
 * before they ever train anything themselves. The model itself is unchanged:
 * same from-scratch architecture in js/model.js, trained here with real SGD.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const src =
  fs.readFileSync(path.join(ROOT, 'js/tokenizer.js'), 'utf8') + '\n' +
  fs.readFileSync(path.join(ROOT, 'js/model.js'), 'utf8') +
  '\nglobalThis.NovaTokenizer = NovaTokenizer; globalThis.Nova1Model = Nova1Model;';
eval(src);

// Tiny-GPT config (minGPT/microgpt style — see js/model.js header)
const CONFIG = { blockSize: 48, dModel: 48, nHead: 2, nLayer: 2, lr: 1e-2, lrDecay: 0.985, lrFloor: 1e-3, batch: 12 };
const EPOCHS = parseInt(process.env.EPOCHS || '250', 10);
const MAX_WINDOWS = parseInt(process.env.MAX_WINDOWS || '360', 10);

(async () => {
  const corpus = fs.readFileSync(path.join(__dirname, 'corpus.txt'), 'utf8');
  console.log(`corpus: ${corpus.length.toLocaleString()} chars, ${(corpus.length / 1024).toFixed(1)} KB`);
  let m;
  const cpPath = path.join(ROOT, 'js/base-checkpoint.js');
  const resumePath = path.join(__dirname, 'last-checkpoint.json');
  let json = null;
  if (process.env.CONTINUE === '1') {
    if (fs.existsSync(resumePath)) {
      json = JSON.parse(fs.readFileSync(resumePath, 'utf8'));
      console.log('resuming from train/last-checkpoint.json');
    } else if (fs.existsSync(cpPath)) {
      const cpSrc = fs.readFileSync(cpPath, 'utf8');
      json = JSON.parse(cpSrc.slice(cpSrc.indexOf('{'), cpSrc.lastIndexOf('}') + 1));
    }
  }
  if (json) {
    m = Nova1Model.fromJSON(json);
    m._base = false;
    console.log('continuing from existing checkpoint (loss ' + (m.lastLoss || 0).toFixed(4) + ', ' + m.trainSteps.toLocaleString() + ' steps)');
  } else {
    m = new Nova1Model(CONFIG);
  }
  const t0 = Date.now();
  if (process.env.CONTINUE === '1') {
    m.config.lr = (m.lastLoss && m.lastLoss < 1) ? 1e-3 : 3e-3; // gentle when near-converged
  }
  const res = await m.train(corpus, {
    epochs: EPOCHS,
    epochCap: 1000,
    maxWindows: MAX_WINDOWS,
    onProgress: (p) => {
      if (p.sample !== null) {
        console.log(`epoch ${p.epoch}/${p.epochs} · loss ${p.loss.toFixed(4)} · sample: ${JSON.stringify(p.sample.slice(0, 90))}`);
        // resumable checkpoint after every epoch — survives interruption
        fs.writeFileSync(path.join(__dirname, 'last-checkpoint.json'), JSON.stringify(m.toJSON()));
      }
    },
  });
  console.log(`done: loss ${res.loss.toFixed(4)} after ${res.steps.toLocaleString()} steps in ${((Date.now() - t0) / 1000).toFixed(0)}s`);

  const cp = m.toJSON();
  cp.base = true;
  cp.baseNote = 'Base conversational training from train/corpus.txt';
  const out =
    '/* Nova 1.0 base checkpoint — generated by train/train.js from train/corpus.txt. ' + new Date().toISOString() + ' */\n' +
    '/* This is the default weights set every visitor loads. Loss ' + res.loss.toFixed(4) + ', ' + res.steps.toLocaleString() + ' SGD steps. */\n' +
    'window.NOVA_BASE_CHECKPOINT = ' + JSON.stringify(cp) + ';\n';
  fs.writeFileSync(path.join(ROOT, 'js/base-checkpoint.js'), out);
  if (fs.existsSync(resumePath)) fs.unlinkSync(resumePath);
  console.log('written js/base-checkpoint.js (' + Math.round(out.length / 1024) + ' KB)');

  // sanity: reload + sample
  const m2 = Nova1Model.fromJSON(JSON.parse(JSON.stringify(cp)));
  for (const seed of ['Hello', 'What is Nova', 'Tell me a joke', 'How do you work']) {
    console.log('seed ' + JSON.stringify(seed) + ' -> ' + JSON.stringify(m2.generate(90, 0.85, m2.tokenizer.encode(seed).slice(0, -1)).trim()));
  }
})().catch((e) => { console.error('TRAIN FAILED', e); process.exit(1); });
