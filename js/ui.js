/**
 * Trims a raw continuation to a tidy reply-sized chunk: cut at the first
 * sentence end (or a line break) within a readable window. The text itself
 * is untouched model output — only where we stop reading is chosen.
 */

/**
 * Models are trained on "You: <q>\nNova: <a>" turns. A completion may echo
 * the turn marker or bleed into the next question — keep only Nova's answer.
 */
function extractNovaTurn(text) {
  let t = String(text || '');
  const i = t.indexOf('Nova:');
  if (i !== -1) t = t.slice(i + 5);
  // stop if generation bled into the next user turn
  const j = t.indexOf('You:');
  if (j !== -1) t = t.slice(0, j);
  return t.trim();
}

function trimReply(text) {
  let t = String(text).replace(/\s+$/, '');
  if (!t) return t;
  const window = t.slice(0, 300);
  let cut = -1;
  for (let i = 0; i < window.length; i++) {
    if ((window[i] === '.' || window[i] === '!' || window[i] === '?') &&
        (i + 1 >= window.length || window[i + 1] === ' ' || window[i + 1] === '\n')) {
      cut = i + 1;
      break;
    }
  }
  if (cut < 0) {
    // no sentence end in range: cut at the last word boundary, never mid-word
    const sp = window.lastIndexOf(' ');
    if (sp > 30) return window.slice(0, sp).trim();
  }
  if (cut === -1) {
    const nl = window.indexOf('\n', 20);
    cut = nl !== -1 ? nl : 220;
  }
  return t.slice(0, cut).trim();
}

async function handleSend() {
  const input = $('input');
  const text = input.value.trim();
  if (!text || generating) return;

  const model = activeModel();
  if (!model) return;

  let chat = activeChat();
  if (!chat) {
    newChat();
    chat = activeChat();
  }

  const meta = MODELS.find((m) => m.id === activeModelId);
  chat.messages.push({ role: 'user', content: text, ts: Date.now() });
  if (chat.title === 'New chat') {
    chat.title = text.length > 42 ? text.slice(0, 42) + '…' : text;
  }
  input.value = '';
  autosize(input);
  updateSendState();
  NovaStorage.set('nova.chats.v1', chats);
  renderChatList();
  renderMessages();

  generating = true;
  const loading = el('div', 'loading-row', `
    <div class="avatar"><svg width="17" height="17" viewBox="0 0 32 32" aria-hidden="true"><defs><linearGradient id="lg2" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#7c5cff"/><stop offset="1" stop-color="#4dd6ff"/></linearGradient></defs><path fill="url(#lg2)" d="M16 1c1.4 8.2 5.4 12.2 14 14-8.6 1.8-12.6 5.8-14 14-1.4-8.2-5.4-12.2-14-14 8.6-1.8 12.6-5.8 14-14z"/></svg></div>
    <div class="dots"><i></i><i></i><i></i></div>`);
  $('chatInner').appendChild(loading);
  scrollChat();

  try {
    // Generation seeds with your message: Nova continues it from its own
    // next-token predictions. Real sampling from real weights, never scripted.
    // chat-turn format: seed with the user's turn, Nova answers in its own turn
    const meta0 = MODELS.find((m) => m.id === activeModelId);
    const chatTurn = !!(meta0 && meta0.chatTurn);
    const seedIds = model.tokenizer.encode((chatTurn ? 'You: ' : '') + text).slice(0, -1);
    const maxTokens = Math.min(340, 60 + Math.floor(text.length / 2));
    // live thinking: stream tokens into the bubble as the model samples them
    const liveRow = el('div', 'msg assistant thinking', `
      <div class="avatar"><svg width="17" height="17" viewBox="0 0 32 32" aria-hidden="true"><defs><linearGradient id="lg3" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#7c5cff"/><stop offset="1" stop-color="#4dd6ff"/></linearGradient></defs><path fill="url(#lg3)" d="M16 1c1.4 8.2 5.4 12.2 14 14-8.6 1.8-12.6 5.8-14 14-1.4-8.2-5.4-12.2-14-14 8.6-1.8 12.6-5.8 14-14z"/></svg></div>
      <div class="bubble"><span class="thinking-label">Thinking…</span></div>`);
    $('chatInner').appendChild(liveRow);
    scrollChat();
    let lastPaint = 0;
    const raw = await new Promise((resolve, reject) => {
      setTimeout(() => {
        model.generateAsync(maxTokens, 0.62, seedIds, (partial) => {
          const now = Date.now();
          if (now - lastPaint > 40) { // throttle paints
            lastPaint = now;
            const bubble = liveRow.querySelector('.bubble');
            const shown = chatTurn ? extractNovaTurn(partial) : partial;
            if (bubble && shown.trim()) {
              bubble.innerHTML = '<span class="thinking-label">Thinking…</span>' + renderMarkdown(shown);
            }
            scrollChat();
          }
        }).then(resolve, reject);
      }, 30);
    });
    liveRow.remove();
    const out = trimReply(chatTurn ? extractNovaTurn(raw) : raw);

    let content;
    const clean = out.trim();
    if (!model.trained) {
      content =
        `> **${escapeHtml(meta.name)} has not been trained yet.** Its weights are randomly initialized, so what you see below is the model's genuine raw prediction — real neural network output, but it carries no meaning yet.\n\n` +
        `**What to do:** tap **Train** in the top bar and paste some text. It will train right here in your browser and replies will start reflecting that data.\n\n` +
        'Raw model output for this input:\n\n```\n' + (clean === '' ? '(the untrained model produced an empty completion)' : clean) + '\n```';
    } else if (clean === '') {
      content = 'The model produced an empty continuation for this input. Try rephrasing, or train it on more (or more varied) text.';
    } else {
      content = clean;
    }

    chat.messages.push({ role: 'assistant', content, model: meta.name, ts: Date.now() });
  } catch (err) {
    console.error(err);
    chat.messages.push({
      role: 'assistant',
      error: true,
      content: `**Something went wrong while generating.**\n\n\`${escapeHtml(err.message || String(err))}\``,
      model: meta.name,
      ts: Date.now(),
    });
  } finally {
    loading.remove();
    generating = false;
    NovaStorage.set('nova.chats.v1', chats);
    renderChatList();
    renderMessages();
  }
}

/** Runs generation in a microtask so the loading row paints first. */
function sampleAsync(model, seedIds, maxTokens, temp) {
  return new Promise((resolve, reject) => {
    setTimeout(() => {
      try {
        resolve(model.generate(maxTokens, temp, seedIds));
      } catch (e) { reject(e); }
    }, 30);
  });
}

