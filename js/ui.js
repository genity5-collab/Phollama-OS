function escapeHtml(s) {
  return String(s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

function el(tag, cls, html) {
  const e = document.createElement(tag);
  if (cls) e.className = cls;
  if (html !== undefined) e.innerHTML = html;
  return e;
}

/* ---------------- markdown-lite renderer (safe) ---------------- */

function renderMarkdown(src) {
  if (src === null || src === undefined) return '';
  const blocks = String(src).split('```');

  const renderInline = (s) => s
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/`([^`\n]+)`/g, '<code class="inline">$1</code>');

  const renderText = (text) => {
    const lines = text.split('\n');
    let out = '', i = 0;
    let listType = null, listItems = [];
    const flushList = () => {
      if (!listType) return;
      out += `<${listType}>` + listItems.map((li) => `<li>${li}</li>`).join('') + `</${listType}>`;
      listType = null; listItems = [];
    };
    while (i < lines.length) {
      const raw = lines[i];
      const esc = escapeHtml(raw);
      const ul = esc.match(/^\s*[-*]\s+(.*)$/);
      const ol = esc.match(/^\s*\d+[.)]\s+(.*)$/);
      if (ul) {
        if (listType !== 'ul') { flushList(); listType = 'ul'; }
        listItems.push(renderInline(ul[1]));
      } else if (ol) {
        if (listType !== 'ol') { flushList(); listType = 'ol'; }
        listItems.push(renderInline(ol[1]));
      } else {
        flushList();
        if (esc.trim() !== '') {
          out += `<p>${renderInline(esc).replace(/\n/g, '<br>')}</p>`;
        }
      }
      i++;
    }
    flushList();
    return out;
  };

  let html = '';
  for (let b = 0; b < blocks.length; b++) {
    if (b % 2 === 1) {
      let code = blocks[b];
      code = code.replace(/^[a-zA-Z0-9+#-]*\n?/, '');
      html += `<pre class="codeblock"><code>${escapeHtml(code.replace(/\n$/, ''))}</code></pre>`;
    } else if (blocks[b].trim() !== '' || b === blocks.length - 1) {
      html += renderText(blocks[b]);
    }
  }
  return html;
}

/* ---------------- model management ---------------- */

function modelKey(id) { return 'nova.model.' + id + '.v3'; }

function activeModel() { return models[activeModelId] || null; }

/** Loads (lazily) a model: own browser checkpoint > shipped base > fresh. */
function loadModel(id) {
  if (models[id]) return models[id];
  let m = null;
  let base = false;
  const saved = NovaStorage.get(modelKey(id), null);
  if (saved) {
    try { m = Nova1Model.fromJSON(saved); } catch (e) { console.warn('Saved checkpoint unreadable.', e); }
  }
  if (!m && window.NOVA_BASE_CHECKPOINTS && window.NOVA_BASE_CHECKPOINTS[id]) {
    try {
      m = Nova1Model.fromJSON(window.NOVA_BASE_CHECKPOINTS[id]);
      m._base = true; // shipped base training (train/train.js)
    } catch (e) { console.warn('Base checkpoint unreadable.', e); }
  }
  if (!m) m = new Nova1Model();
  models[id] = m;
  return m;
}

function selectModel(id) {
  if (generating) { toast('Please wait for the reply to finish.', 'err'); return; }
  if (!MODELS.some((m) => m.id === id)) return;
  activeModelId = id;
  NovaStorage.set('nova.activeModel.v1', id);
  $('modelBtnLabel').textContent = MODELS.find((m) => m.id === id).name;
  updateTrainButtonLabel();
  renderModelMenu();
  renderMessages();
  closeModelMenu();
}

function saveModel(id) {
  const m = models[id];
  if (!m) return;
  const r = NovaStorage.set(modelKey(id), m.toJSON());
  if (!r.ok) handleSaveFailure(r, 'model weights');
}

function handleSaveFailure(r, what) {
  if (r.reason === 'quota') {
    toast(`Browser storage is full — ${what} could not be saved for this session.`, 'err');
  } else if (r.reason !== 'unavailable') {
    toast(`Could not save ${what} to storage.`, 'err');
  }
}

