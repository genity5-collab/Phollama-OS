function renderMessages() {
  const inner = $('chatInner');
  inner.innerHTML = '';
  const chat = activeChat();
  if (!chat || chat.messages.length === 0) {
    inner.innerHTML = welcomeHTML();
    return;
  }
  for (const m of chat.messages) {
    const row = el('div', 'msg ' + m.role + (m.error ? ' error' : ''));
    const roleName = m.role === 'user' ? 'You' : (m.model || 'Nova');
    row.innerHTML = avatarHTML(m.role === 'user') + `
      <div class="bubble"><div class="role">${escapeHtml(roleName)}</div>${renderMarkdown(m.content)}</div>`;
    inner.appendChild(row);
  }
  scrollChat();
}

